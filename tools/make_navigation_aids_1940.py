#!/usr/bin/env python3
"""Hand-authored 1940s navigation-aid dataset for the Channel theatre (P18).

PROVENANCE
----------
Every site is a real 1940s radio station, radio-range beacon, direction-finding station or night-fighter
airfield, cited per record. Coordinates are real WGS84 positions at the station / airfield level (the mast,
aerial array or approach lights are placed by the kit around that point). No third-party geometry, imagery or
data file was copied.

Kinds:
  radio_beacon   a radio-range beacon - a guyed mast and a transmitting hut on a circular earth mat, with
                 shorter aerial masts.
  df_station     a direction-finding (DF) station - a four-mast Adcock aerial array on a circular earth mat
                 around an operator hut.
  beacon_mast    a tall guyed beacon / broadcast mast (the Rugby / Droitwich silhouette) with a tuning hut
                 and guy-anchor blocks.
  night_lighting an outer approach-lighting array for night sorties - elevated lamps with pundit markers, an
                 outer marker and a controller's caravan on the approach.

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/navigation_aids_1940.json : {"sites":[{id,name,kind,lat,lon,heading_deg,size,team,source}]}

Usage: python tools/make_navigation_aids_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored 1940s navigation-aid sites (no third-party licence); generated by "
        "tools/make_navigation_aids_1940.py. Positions are real WGS84 station / airfield coordinates cited "
        "per record; the mast, aerial array or approach lights are placed by seed around that point. The "
        "scenery is procedural low-poly toon from GroundKit primitives; no third-party geometry, imagery or "
        "data file was copied.")

WP = "Wikipedia (CC BY-SA 4.0, https://www.wikipedia.org)"

# (id, name, kind, lat, lon, heading_deg, size, source)
SITES = [
    # ---- tall beacon / broadcast masts (Rugby, Droitwich) ----
    ("mast_rugby", "Rugby Radio Station mast", "beacon_mast", 52.3750, -1.1900, 0.0, 3,
     WP + " 'Rugby Radio Station': the giant 1926 VLF mast, then the wartime transmitting station"),
    ("mast_droitwich", "Droitwich Transmitting Station masts", "beacon_mast", 52.2800, -2.1300, 0.0, 3,
     WP + " 'Droitwich Transmitting Station': the 1934 BBC long-wave masts"),
    ("mast_brookmans_park", "Brookmans Park transmitting station", "beacon_mast", 51.7250, -0.1700, 0.0, 2,
     WP + " 'Brookmans Park transmitting station': the 1929 BBC London twin-mast station"),
    ("mast_daventry", "Daventry transmitting station", "beacon_mast", 52.1850, -1.1550, 0.0, 2,
     WP + " 'Daventry transmitting station': the BBC Empire and wartime station"),
    # ---- radio-range / navigational beacons ----
    ("beacon_ventnor", "Ventnor radio beacon", "radio_beacon", 50.5950, -1.2050, 0.0, 2,
     WP + " 'Ventnor': the Isle of Wight coastal radio / DF station site of the 1940s"),
    ("beacon_duxford", "Duxford radio range beacon", "radio_beacon", 52.0900, 0.1310, 0.0, 1,
     WP + " 'Duxford': the RAF radio-range and navigational aid station"),
    ("beacon_trimingham", "Trimmingham navigation beacon", "radio_beacon", 52.9000, 1.6000, 0.0, 2,
     WP + " 'Trimingham' / RAF Oboe: the Norfolk coastal navigational-beacon site"),
    ("beacon_lydd", "Lydd radio beacon", "radio_beacon", 50.9500, 0.9100, 0.0, 1,
     WP + " 'Lydd' / 'Denge': the Romney Marsh radio and sound-ranging station"),
    # ---- direction-finding (DF) stations ----
    ("df_swingate", "Swingate DF station", "df_station", 51.1350, 1.3400, 0.0, 2,
     WP + " 'Swingate' / 'Dover': the RAF coastal direction-finding station above Dover"),
    ("df_dungeness", "Dungeness DF station", "df_station", 50.9100, 0.9700, 0.0, 1,
     WP + " 'Dungeness': the RAF direction-finding and radar site on the Kentish coast"),
    ("df_bawdsey", "Bawdsey DF station", "df_station", 51.9950, 1.4000, 0.0, 2,
     WP + " 'RAF Bawdsey': the Suffolk coastal station (Chain Home radar and radio direction finding)"),
    # ---- night-sortie approach lighting (night-fighter airfields) ----
    ("night_ford", "RAF Ford night-lighting", "night_lighting", 50.8030, -0.5780, 0.0, 2,
     WP + " 'RAF Ford': the Sussex night-fighter airfield with its Drem/outer approach lighting"),
    ("night_debden", "RAF Debden night-lighting", "night_lighting", 51.9950, 0.3300, 0.0, 2,
     WP + " 'RAF Debden': the Essex night-fighter airfield of 1940"),
    ("night_middle_wallop", "RAF Middle Wallop night-lighting", "night_lighting", 51.1500, -1.5700, 0.0, 1,
     WP + " 'RAF Middle Wallop': the Hampshire night-fighter airfield with approach lighting"),
]

KINDS = ("radio_beacon", "df_station", "beacon_mast", "night_lighting")


def main():
    recs = []
    for rid, name, kind, lat, lon, hdg, size, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, heading_deg=hdg,
                         size=size, team="Allies", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    assert len(recs) >= 12, "need a spread of navigation-aid sites"
    _write("navigation_aids_1940.json", {"_note": NOTE, "sites": recs})
    print(f"navigation_aids_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
