"""Hand-authored 1940s coastal / seaside landmark dataset for the Channel theatre (P14).

PROVENANCE
----------
Every site is a real, documented seaside landmark cited per record, placed at its real WGS84 position. The
builders live in scripts/ground/landmarks.gd build() as new ids; this file supplies the positions.

Kinds (all new landmarks.build() ids):
  martello_tower      a Martello tower (the Kent / Sussex coast defensive towers, ~1805-1812)
  coastguard_station  an HM Coastguard station / look-out (watch house, turret, rocket shed)
  lifeboat_station    an RNLI lifeboat station (boathouse, slipway, crew room)
  lido                a 1930s open-air seaside lido (pool, terrace, diving boards, changing rooms)
  bandstand           a seaside promenade bandstand (dome on columns)
  holiday_camp        a seaside holiday camp (Butlin's style), requisitioned as a military camp in 1940

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/coastal_landmarks_1940.json : {"sites":[{id,name,kind,lat,lon,size,team,source}]}

Usage: python tools/make_coastal_landmarks_1940.py
"""
