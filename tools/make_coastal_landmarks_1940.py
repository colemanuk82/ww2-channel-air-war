KINDS = ("martello_tower", "coastguard_station", "lifeboat_station", "lido", "bandstand", "holiday_camp")


def main():
    recs = []
    for rid, name, kind, lat, lon, size, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, size=size, team="Allies", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    _write("coastal_landmarks_1940.json", {"_note": NOTE, "sites": recs})
    print(f"coastal_landmarks_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
