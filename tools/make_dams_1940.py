#!/usr/bin/env python3
"""Hand-authored Dam Busters dam dataset for the Channel theatre (P3).

PROVENANCE
----------
Every dam is a real structure at its real WGS84 position, taken from the cited source (the coordinates
were verified in the implementation pass, per the program brief - two sites differ a few km from the
brief's planning figures):
  Möhne   51.4893, 8.0588   Wikipedia, Möhne Reservoir (dam 51.489307N 8.058772E)
  Eder    51.1833, 8.9667   sited on the Edersee inside the playable bounds (the 1914 dam wall is at
                            51.18333N 9.05889E, ~4 km east of the heightmap edge lon 9.0 - see _note)
  Sorpe   51.3503, 7.9675   Wikipedia, Sorpe Dam (51.35028N 7.96750E)
  Ennepe  51.2411, 7.4089   Wikipedia (de), Ennepetalsperre (51 14 28 N 7 24 32 E)
  Lister  51.0939, 7.8375   Wikipedia (de), Listertalsperre (51 5 38 N 7 50 15 E)
  Diemel  51.3722, 8.7239   Wikipedia, Diemelsee (51.37222N 8.72389E)
Operation Chastise, 16-17 May 1943 (Wikipedia, Operation Chastise): primary targets Möhne, Sorpe, Eder;
secondary (reserve) targets Lister, Ennepe, Diemel.

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/dams_1940.json : {"dams":[{id,name,kind,lat,lon,heading_deg,wall_len_m,wall_h_m,reservoir_km2,team,source}]}

Usage: python tools/make_dams_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored Dam Busters dam sites (no third-party licence); generated by "
        "tools/make_dams_1940.py. Positions are real WGS84 coordinates from the cited sources; the "
        "Edersee (Eder) site is placed at 51.1833, 8.9667 (a real point on the reservoir) to stay inside "
        "the playable heightmap (LON_MAX 9.0) - the 1914 wall itself stands at 51.18333, 9.05889.")

# (id, name, lat, lon, heading_deg, wall_len_m, wall_h_m, reservoir_km2, source)
DAMS = [
    ("moehne", "Möhne Dam (Möhnetalsperre)", 51.4893, 8.0588, 340.0, 650.0, 40.0, 10.37,
     "Wikipedia, Möhne Reservoir (dam 51.489307N 8.058772E)"),
    ("eder", "Eder Dam (Edersee)", 51.1833, 8.9667, 60.0, 400.0, 48.0, 11.8,
     "Wikipedia, Edersee Dam (wall 51.18333N 9.05889E; feature placed on the reservoir inside bounds)"),
    ("sorpe", "Sorpe Dam (Sorpetalsperre)", 51.3503, 7.9675, 300.0, 700.0, 69.0, 3.30,
     "Wikipedia, Sorpe Dam (51.35028N 7.96750E)"),
    ("ennepe", "Ennepe Dam (Ennepetalsperre)", 51.2411, 7.4089, 130.0, 320.0, 51.0, 1.03,
     "Wikipedia (de), Ennepetalsperre (51 14 28 N 7 24 32 E)"),
    ("lister", "Lister Dam (Listertalsperre)", 51.0939, 7.8375, 160.0, 264.0, 42.0, 1.70,
     "Wikipedia (de), Listertalsperre (51 5 38 N 7 50 15 E)"),
    ("diemel", "Diemel Dam (Diemeltalsperre)", 51.3722, 8.7239, 220.0, 194.0, 42.0, 1.65,
     "Wikipedia, Diemelsee (51.37222N 8.72389E)"),
]


def main():
    recs = []
    for rid, name, lat, lon, hdg, wl, wh, res, source in DAMS:
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind="dam", lat=lat, lon=lon, heading_deg=hdg,
                         wall_len_m=wl, wall_h_m=wh, reservoir_km2=res, team="Axis", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    assert len(recs) >= 6, "Dam Busters list is short"
    _write("dams_1940.json", {"_note": NOTE, "dams": recs})
    print(f"dams_1940.json: {len(recs)} dams")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
