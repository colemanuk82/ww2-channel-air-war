"""Hand-authored 1940s industry / docks datasets for the Channel theatre.

PROVENANCE
----------
Every coordinate, name, kind and size below is HAND-AUTHORED from period knowledge of the
places (gasworks, collieries, mills, breweries, power stations, shipyards, docks and piers of
the Thames/Medway, the Midlands, Normandy/Pas-de-Calais/Flanders, the Low Countries and the
Ruhr). Nothing here is copied from a third-party dataset or licence - there is no licence
issue and no attribution is required for these two files (OSM, where used elsewhere, is
already attributed in ATTRIBUTION.md).

OUTPUTS (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/industry_1940.json : {"sites":[{id,name,kind,lat,lon,size,team}]}
  data/docks_1940.json    : {"piers":[...], "docks":[...]}  (same record shape + kind)

TEAM RULE (no Godot engine available to Python; GroundKit.side_at is a GDScript function):
  In 1940 the front ran down the Channel: Britain = Allies, occupied France/Belgium/Netherlands
  and Germany = Axis. We approximate the British Isles with the box  lat > 50.4 and lon < 1.6
  (west/north of the Strait of Dover); everything south-east of that line is Axis. This is the
  same split the game's map uses and it is applied here explicitly, per record.

Usage: python tools/make_industry_1940.py
"""
