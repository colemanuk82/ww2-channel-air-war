def _records(rows, kinds):
    out = []
    for rid, name, kind, lat, lon, size in rows:
        assert kind in kinds, f"{rid}: unknown kind {kind}"
        out.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, size=size,
                        team=team_for(lat, lon)))
    return out


def _check_unique(recs, where):
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), f"duplicate id in {where}"


def main():
    sites = _records(INDUSTRY, INDUSTRY_KINDS)
    piers = _records(PIERS, PIER_KINDS)
    docks = _records(DOCKS, DOCK_KINDS)
    _check_unique(sites, "industry")
    _check_unique(piers, "piers")
    _check_unique(docks, "docks")
    assert len(sites) >= 40, f"industry: only {len(sites)} sites"

    _write("industry_1940.json", {"_note": NOTE, "sites": sites})
    _write("docks_1940.json", {"_note": NOTE, "piers": piers, "docks": docks})
    print(f"industry_1940.json: {len(sites)} sites")
    print(f"docks_1940.json: {len(piers)} piers, {len(docks)} docks")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
