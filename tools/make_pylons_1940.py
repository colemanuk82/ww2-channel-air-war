#!/usr/bin/env python3
"""Hand-authored 1927-35 National Grid period pylons / overhead-line fallback (P5).

PROVENANCE
----------
This is the CURATED FALLBACK for the period grid, used only when the real OSM `power` layer cannot be
fetched (the runtime prefers data/osm/power.json). Every line links two real, documented CEB / National
Grid places, cited per record; the polyline is a deliberately simplified chord between them (a fallback,
not a survey). Coordinates are real WGS84 from the cited sources.

The CEB 132 kV National Grid (Electricity (Supply) Act 1926) ran first as a "gridiron" from 1927 and was
complete by September 1933 (Wikipedia, National Grid (UK); Wikipedia, Central Electricity Board). Key
South-East grid points cited below: Northfleet, the largest 132 kV switching station in the South-East
England scheme (Grace's Guide, Central Electricity Board); the CEB's high-voltage laboratories at Croydon
and Waddon; Barking / Battersea / Deptford / Willesden London generating and grid points.

OUTPUT (deterministic - fixed ordering; re-running reproduces byte-identical JSON):
  data/pylons_1940.json : {"lines":[{id,name,k:"line",v:132000,pts:[[lat,lon],...],source}]}

Usage: python tools/make_pylons_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored 1927-35 National Grid period-grid fallback (no third-party licence); generated by "
        "tools/make_pylons_1940.py. Each line links two real, cited CEB / National Grid places as a "
        "simplified chord - a fallback for the period grid, not a survey.")

# (id, name, [ [lat,lon], ... ], source)
LINES = [
    ("northfleet_gravesend", "132 kV Northfleet - Gravesend (South-East England scheme)", 
     [[51.4400, 0.3400], [51.4415, 0.3685]],
     "Grace's Guide, Central Electricity Board: Northfleet, largest 132 kV switching station in the "
     "South-East England scheme; Wikipedia, Northfleet (51.44N 0.34E) / Gravesend (51.4415N 0.3685E)"),
    ("northfleet_croydon", "132 kV Northfleet - Croydon grid line (South-East England scheme)",
     [[51.4400, 0.3400], [51.4050, 0.1200], [51.3714, -0.1038]],
     "Wikipedia, Central Electricity Board (CEB laboratories at Croydon / Waddon); CEB South-East England "
     "132 kV scheme via Northfleet switching station; endpoints Wikipedia, Northfleet / Croydon"),
    ("croydon_waddon", "132 kV Croydon - Waddon grid link (CEB laboratories)",
     [[51.3714, -0.1038], [51.3643, -0.1125]],
     "Wikipedia, Central Electricity Board: laboratories at Croydon and Waddon; place coords Wikipedia, "
     "Croydon (51.3714N 0.1038W) / Waddon (51.3643N 0.1125W)"),
    ("willesden_battersea", "132 kV Willesden - Battersea London grid ring",
     [[51.5468, -0.2295], [51.4817, -0.1447]],
     "Wikipedia, National Grid (UK): 1926 Central Electricity Board London 132 kV grid; place coords "
     "Wikipedia, Willesden (51.5468N 0.2295W) / Battersea Power Station (51.4817N 0.1447W)"),
    ("northfleet_ipswich", "132 kV Northfleet - Ipswich grid line",
     [[51.4400, 0.3400], [51.7500, 0.7500], [52.0594, 1.1556]],
     "Wikipedia, National Grid (UK): South-East England 132 kV scheme (est. 1927-33); endpoints Wikipedia, "
     "Northfleet / Ipswich (52.0594N 1.1556E); mid-point schematic"),
]

V = 132000


def main():
    recs = []
    for rid, name, pts, source in LINES:
        for la, lo in pts:
            assert -4.6 <= lo <= 9.0 and 48.9 <= la <= 53.0, f"{rid}: lat/lon out of bounds ({la},{lo})"
        recs.append(dict(id=rid, name=name, k="line", v=V, pts=pts, source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    _write("pylons_1940.json", {"_note": NOTE, "lines": recs})
    print(f"pylons_1940.json: {len(recs)} lines")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
