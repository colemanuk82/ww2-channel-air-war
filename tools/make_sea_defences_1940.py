KINDS = ("minefield", "boom", "blockship", "sea_fort", "obstacles", "wreck")
STYLES = ("", "army_fort", "navy_fort", "tower")


def main():
    recs = []
    for rid, name, kind, lat, lon, hdg, length_m, rows, team, style, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert team in ("Axis", "Allies"), f"{rid}: bad team {team}"
        assert style in STYLES, f"{rid}: bad style {style}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, heading_deg=hdg,
                         length_m=length_m, rows=rows, team=team, style=style, source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    _write("sea_defences_1940.json", {"_note": NOTE, "sites": recs})
    print(f"sea_defences_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
