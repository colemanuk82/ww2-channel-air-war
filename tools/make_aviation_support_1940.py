#!/usr/bin/env python3
"""Hand-authored 1940s aviation-support dataset for the Channel theatre (P16).

PROVENANCE
----------
Every site is a real 1940 seaplane / flying-boat station, airship / blimp mooring station or kite-balloon
(Balloon Command) site, cited per record. Coordinates are real WGS84 positions at the station / locality level
(the slipway, shed, mast and balloons are placed by the kit around that point). No third-party geometry,
imagery or data file was copied.

Kinds:
  seaplane_base     a seaplane / flying-boat station - the Sunderland stations: an inclined slipway to the
                    water, a concrete apron, T2 hangars, a control / watch office, mooring buoys and a
                    moored flying boat.
  airship_station   an airship / blimp mooring station - a long airship shed, a tall lattice mooring mast,
                    a hydrogen store and a windbreak.
  kite_balloon_site a kite-balloon site - a balloon shed, winch lorries and kite balloons on their cables
                    (the 1940 Balloon Command / balloon-barrage stations).

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/aviation_support_1940.json : {"sites":[{id,name,kind,lat,lon,heading_deg,size,team,source}]}

Usage: python tools/make_aviation_support_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored 1940s aviation-support sites (no third-party licence); generated by "
        "tools/make_aviation_support_1940.py. Positions are real WGS84 station / locality coordinates cited "
        "per record; the slipway, shed, mast and balloons are placed by seed around that point. The scenery "
        "is procedural low-poly toon from GroundKit primitives; no third-party geometry, imagery or data "
        "file was copied.")

WP = "Wikipedia (CC BY-SA 4.0, https://www.wikipedia.org)"

# (id, name, kind, lat, lon, heading_deg, size, source)
SITES = [
    # ---- seaplane / flying-boat stations (the Sunderland stations) ----
    ("seaplane_calshot", "RAF Calshot flying-boat station", "seaplane_base", 50.8189, -1.3078, 96.0, 3,
     WP + " 'RAF Calshot': the Southampton Water flying-boat station, a main Sunderland base of 1938-40"),
    ("seaplane_mount_batten", "RAF Mount Batten flying-boat station", "seaplane_base", 50.3590, -4.1390, 180.0, 2,
     WP + " 'RAF Mount Batten' / 'Plymouth Sound': the Plymouth flying-boat station for 10 Sqn Sunderlands"),
    ("seaplane_felixstowe", "RAF Felixstowe flying-boat station", "seaplane_base", 51.9450, 1.3200, 110.0, 2,
     WP + " 'Felixstowe' / 'Seaplane Experimental Station': the East Anglian flying-boat station and marine "
     "aircraft experimental establishment"),
    ("seaplane_hamble", "Hamble seaplane base", "seaplane_base", 50.8550, -1.3100, 158.0, 2,
     WP + " 'Hamble-le-Rice': the Hamble river seaplane works and slipway used by Supermarine / Airspeed"),
    ("seaplane_lee_on_solent", "RAF Lee-on-Solent seaplane base", "seaplane_base", 50.8120, -1.2080, 180.0, 2,
     WP + " 'RNAS Lee-on-Solent (HMS Daedalus)': the Solent seaplane and flying-boat station"),
    ("seaplane_poole", "Poole Harbour flying-boat base", "seaplane_base", 50.7100, -1.9900, 90.0, 1,
     WP + " 'Poole Harbour': the harbour seaplane / flying-boat base used by BOAC and the RAF"),
    # ---- airship / blimp mooring stations ----
    ("airship_cardington", "RAF Cardington airship station", "airship_station", 52.1130, -0.4200, 90.0, 3,
     WP + " 'RAF Cardington': the airship station and shed whose R101 was built; a wartime balloon depot"),
    ("airship_pulham", "RNAS Pulham airship station", "airship_station", 52.4230, 1.2460, 90.0, 2,
     WP + " 'RNAS Pulham' / 'Pulham St Mary': the Norfolk airship station with its giant shed"),
    ("airship_kingsnorth", "RNAS Kingsnorth airship station", "airship_station", 51.4200, 0.6000, 0.0, 2,
     WP + " 'RNAS Kingsnorth' / 'Kingsnorth, Kent': the Medway airship station"),
    ("airship_capel", "RNAS Capel airship station", "airship_station", 51.0990, 1.2100, 150.0, 1,
     WP + " 'Capel-le-Ferne': the Kent airship station on the Downs above Folkestone"),
    ("airship_wormwood_scrubs", "Wormwood Scrubs airship shed", "airship_station", 51.5180, -0.2400, 90.0, 1,
     WP + " 'Wormwood Scrubs': the London airship shed and balloon station"),
    # ---- kite-balloon sites (Balloon Command) ----
    ("balloon_stanmore", "RAF Stanmore Park (Balloon Command)", "kite_balloon_site", 51.6180, -0.3080, 0.0, 3,
     WP + " 'RAF Stanmore Park': the headquarters of RAF Balloon Command and a balloon centre"),
    ("balloon_kidbrooke", "No. 1 Balloon Centre, Kidbrooke", "kite_balloon_site", 51.4680, 0.0280, 0.0, 2,
     WP + " 'RAF Balloon Command': No. 1 Balloon Centre, Kidbrooke, the London barrage balloon station"),
    ("balloon_hook", "No. 2 Balloon Centre, Hook", "kite_balloon_site", 51.3700, -0.3000, 0.0, 2,
     WP + " 'RAF Balloon Command': No. 2 Balloon Centre, Hook (Surbiton), a London balloon station"),
    ("balloon_croydon", "No. 3 Balloon Centre, Croydon", "kite_balloon_site", 51.3600, -0.1100, 0.0, 1,
     WP + " 'RAF Balloon Command': No. 3 Balloon Centre, Croydon, a London barrage balloon station"),
]

KINDS = ("seaplane_base", "airship_station", "kite_balloon_site")


def main():
    recs = []
    for rid, name, kind, lat, lon, hdg, size, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, heading_deg=hdg,
                         size=size, team="Allies", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    assert len(recs) >= 12, "need a spread of aviation-support sites"
    _write("aviation_support_1940.json", {"_note": NOTE, "sites": recs})
    print(f"aviation_support_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
