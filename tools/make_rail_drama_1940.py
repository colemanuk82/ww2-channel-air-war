#!/usr/bin/env python3
"""Hand-authored catalogue of famous 1940s (and still-standing) railway viaducts and tunnels in the theatre (P7).

PROVENANCE
----------
rails.json (OSM) carries no bridge/tunnel tags, so the great majority of viaducts and tunnels in the world are
DERIVED from the terrain at runtime (a rail line crossing a dip in the height field is carried on a viaduct, a
line running through a rise enters a tunnel portal). This file is the small hand-authored catalogue of FAMOUS
structures placed at their real, cited WGS84 positions. Every record's `source` names the reference the
coordinate and the span/height were taken from:

  Ouse Valley Viaduct  51.03472, -0.11444  Wikipedia, Ouse Valley Viaduct (37 spans, 450 m, 29 m, 1841)
  Chappel Viaduct      51.92090,  0.75570  Wikipedia, Chappel Viaduct (24 arches, 320 m, 23 m, 1849)
  Digswell Viaduct     51.81830, -0.19470  Wikipedia, Digswell Viaduct / Welwyn Viaduct (475 m, 30 m, 1850)
  Maidenhead Bridge    51.52111, -0.70167  Wikipedia, Maidenhead Railway Bridge / the Sounding Arch (235 m, 9.8 m)
  Box Tunnel           51.42128, -2.22617  Wikipedia, Box Tunnel (centre point; 2.95 km, Brunel, 1841)
  Kilsby Tunnel        52.33100, -1.16400  Wikipedia, Kilsby Tunnel (2.216 km, Robert Stephenson, 1838)
  Severn Tunnel        51.57500, -2.68890  Wikipedia, Severn Tunnel (nominal location; 7.0 km, 1886)
  Thames Tunnel        51.50306, -0.05444  Wikipedia, Thames Tunnel (Rotherhithe-Wapping; 400 m, 1843)

kinds: viaduct (deck on arched piers), tunnel (portal + hillside). heading_deg is the approximate direction the
line runs through the structure; span_m/height_m are the real dimensions from the cited source.

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/rail_drama_1940.json : {"sites":[{id,name,kind,lat,lon,heading_deg,span_m,height_m,team,source}]}

Usage: python tools/make_rail_drama_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored catalogue of famous railway viaducts and tunnels (no third-party licence); generated by "
        "tools/make_rail_drama_1940.py. Positions are real WGS84 coordinates from the cited per-record source. "
        "The bulk of the programme's viaducts and tunnels are DERIVED from the terrain at runtime (see "
        "scripts/ground/rail_kit.gd); this file pins the famous ones to their real positions.")

# (id, name, kind, lat, lon, heading_deg, span_m, height_m, source)
SITES = [
    ("ouse_valley_viaduct", "Ouse Valley Viaduct (Balcombe Viaduct)", "viaduct",
     51.03472, -0.11444, 12.0, 450.0, 29.0,
     "Wikipedia, Ouse Valley Viaduct (51.03472N 0.11444W; Brighton Main Line over the River Ouse, 37 spans, "
     "450 m long, 29 m high, opened 1841)"),
    ("chappel_viaduct", "Chappel Viaduct", "viaduct",
     51.92090, 0.75570, 5.0, 320.0, 23.0,
     "Wikipedia, Chappel Viaduct (51.9209N 0.7557E; Gainsborough Line over the River Colne, 24 arches, "
     "320 m long, 23 m high, 1849)"),
    ("digswell_viaduct", "Digswell Viaduct (Welwyn Viaduct)", "viaduct",
     51.81830, -0.19470, 0.0, 475.0, 30.0,
     "Wikipedia, Digswell Viaduct (51.8183N 0.1947W; East Coast Main Line over the Mimram Valley, 475 m long, "
     "30 m high, 1850)"),
    ("maidenhead_bridge", "Maidenhead Railway Bridge (the Sounding Arch)", "viaduct",
     51.52111, -0.70167, 350.0, 235.0, 10.0,
     "Wikipedia, Maidenhead Railway Bridge (51.52111N 0.70167W; Great Western Main Line over the Thames, "
     "235 m long, 9.8 m high, Brunel, 1839)"),
    ("box_tunnel", "Box Tunnel", "tunnel",
     51.42128, -2.22617, 80.0, 0.0, 0.0,
     "Wikipedia, Box Tunnel (centre 51.42128N 2.22617W; Great Western Main Line through Box Hill, 2.95 km, "
     "Brunel, 1841)"),
    ("kilsby_tunnel", "Kilsby Tunnel", "tunnel",
     52.33100, -1.16400, 150.0, 0.0, 0.0,
     "Wikipedia, Kilsby Tunnel (52.331N 1.164W; West Coast Main Line, 2.216 km, Robert Stephenson, 1838)"),
    ("severn_tunnel", "Severn Tunnel", "tunnel",
     51.57500, -2.68890, 265.0, 0.0, 0.0,
     "Wikipedia, Severn Tunnel (nominal location 51.575N 2.6889W; under the Severn estuary, 7.0 km, 1886)"),
    ("thames_tunnel", "Thames Tunnel (Rotherhithe)", "tunnel",
     51.50306, -0.05444, 290.0, 0.0, 0.0,
     "Wikipedia, Thames Tunnel (51.50306N 0.05444W; Rotherhithe to Wapping, 400 m, Marc and Isambard Brunel, 1843)"),
]

KINDS = ("viaduct", "tunnel")


def main():
    recs = []
    for rid, name, kind, lat, lon, hdg, span, height, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, heading_deg=hdg,
                         span_m=span, height_m=height, team="Allies", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    _write("rail_drama_1940.json", {"_note": NOTE, "sites": recs})
    print(f"rail_drama_1940.json: {len(recs)} structures")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
