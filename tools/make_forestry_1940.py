#!/usr/bin/env python3
"""Hand-authored 1940s forestry dataset for the Channel theatre (P17).

PROVENANCE
----------
Every site is a real Forestry Commission forest or a real wartime timber-camp locality, cited per record.
Coordinates are real WGS84 forest / locality positions (the plantation rows and the camp buildings are placed
by the kit around that point). No third-party geometry, imagery or data file was copied.

Kinds:
  plantation   a Forestry Commission conifer plantation - rows of conifers on a grid with a firebreak, a
               boundary ditch / fence and a forester's hut (the 1919-onwards State forest).
  timber_camp  a wartime timber camp - Nissen-hut lines, a sawmill with a saw bench, timber and pit-prop
               stacks, a loading ramp and a narrow-gauge tramway (the Home Grown Timber Production Dept).

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/forestry_1940.json : {"sites":[{id,name,kind,lat,lon,heading_deg,size,team,source}]}

Usage: python tools/make_forestry_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored 1940s forestry sites (no third-party licence); generated by "
        "tools/make_forestry_1940.py. Positions are real WGS84 forest / locality coordinates cited per "
        "record; the plantation rows and the camp buildings are placed by seed around that point. The scenery "
        "is procedural low-poly toon from GroundKit primitives; no third-party geometry, imagery or data "
        "file was copied.")

WP = "Wikipedia (CC BY-SA 4.0, https://www.wikipedia.org)"
FC = "Forestry Commission (https://www.forestryengland.uk) "

# (id, name, kind, lat, lon, heading_deg, size, source)
SITES = [
    # ---- Forestry Commission plantations ----
    ("forest_thetford", "Thetford Chase plantation", "plantation", 52.4000, 0.7500, 0.0, 3,
     WP + " 'Thetford Forest': the Forestry Commission's largest 1920s-30s conifer plantation (Thetford Chase)"),
    ("forest_alice_holt", "Alice Holt Forest plantation", "plantation", 51.1550, -0.8500, 0.0, 2,
     WP + " 'Alice Holt Forest': the Forestry Commission research forest in Hampshire"),
    ("forest_cannock", "Cannock Chase plantation", "plantation", 52.7500, -2.0000, 0.0, 3,
     WP + " 'Cannock Chase': the Staffordshire heathland planted with Commission conifers"),
    ("forest_new_forest", "New Forest inclosures", "plantation", 50.8700, -1.5700, 0.0, 3,
     WP + " 'New Forest': the Crown inclosures of conifer and the wartime timber felling"),
    ("forest_ashdown", "Ashdown Forest plantation", "plantation", 51.0700, 0.0500, 0.0, 2,
     WP + " 'Ashdown Forest': the East Sussex heathland with its Commission plantations"),
    ("forest_bedgebury", "Bedgebury Forest plantation", "plantation", 51.0600, 0.4500, 0.0, 2,
     WP + " 'Bedgebury Forest' / 'Bedgebury Pinetum': the Kentish Forestry Commission forest"),
    ("forest_savernake", "Savernake Forest plantation", "plantation", 51.4000, -1.6700, 0.0, 2,
     WP + " 'Savernake Forest': the Wiltshire woodland, heavily felled and replanted for the war effort"),
    ("forest_breckland", "Breckland plantation, Brandon", "plantation", 52.4400, 0.6200, 0.0, 2,
     WP + " 'Breckland' / 'Brandon, Suffolk': the East Anglian heath planted with Commission conifers"),
    # ---- wartime timber camps ----
    ("timber_thetford", "Thetford Chase timber camp", "timber_camp", 52.4100, 0.7900, 0.0, 2,
     FC + "/ Wikipedia 'Home Grown Timber Production Department': the wartime camp felling the Thetford Chase plantations"),
    ("timber_alice_holt", "Alice Holt timber camp", "timber_camp", 51.1600, -0.8600, 0.0, 1,
     FC + "/ Wikipedia 'Alice Holt Forest': the wartime sawmill and timber camp in the Hampshire forest"),
    ("timber_breckland", "Breckland timber camp", "timber_camp", 52.4300, 0.6100, 0.0, 2,
     FC + "/ Wikipedia 'Home Grown Timber Production Department': the Breckland wartime timber camp"),
    ("timber_cannock", "Cannock Chase timber camp", "timber_camp", 52.7600, -1.9900, 0.0, 2,
     FC + "/ Wikipedia 'Cannock Chase': the wartime timber camp and sawmill on the Staffordshire chase"),
]

KINDS = ("plantation", "timber_camp")


def main():
    recs = []
    for rid, name, kind, lat, lon, hdg, size, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, heading_deg=hdg,
                         size=size, team="Allies", source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    assert len(recs) >= 10, "need a spread of forestry sites"
    _write("forestry_1940.json", {"_note": NOTE, "sites": recs})
    print(f"forestry_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
