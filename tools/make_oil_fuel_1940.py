#!/usr/bin/env python3
"""Hand-authored 1940s oil and fuel dataset for the Channel theatre (P9).

PROVENANCE
----------
Real tank farms, refineries, petrol depots and gas holders at their real WGS84 positions. Every record's
`source` names the reference for its position:

  Shell Haven      51.5052, 0.4902   Wikipedia, Shell Haven (first Thames Estuary refinery, 1916-1999)
  Coryton          51.5130, 0.5210   Wikipedia, Coryton Refinery (Thames Estuary, opened 1953 on the 1916 site)
  Thames Haven     51.51298, 0.49752 Geograph TQ734823 (Oil Storage Depot) WGS84 51:30.78N 0:29.85E;
                                     Wikipedia, Shell Haven (Thames Haven = the LT&SR port just E of Shell Haven)
  Fawley           50.835, -1.345    Esso Fawley Refinery, Southampton Water (position from the hand-authored
                                     v4.0 WorldPopulator.INDUSTRY cluster; not independently re-verified here)
  Southampton Water 50.895, -1.400   Fawley/Southampton Water marine oil terminal (v4.0 INDUSTRY cluster)
  Port-Jérôme      49.4695, 0.5353   Wikipedia, Notre-Dame-de-Gravenchon / Port of Port-Jérôme (Esso refinery)
  Rouen            49.37, 1.07       Lower Seine refinery zone (v4.0 INDUSTRY cluster)
  Antwerp          51.26, 4.35       Antwerp Scheldt oil and chemical works (v4.0 INDUSTRY cluster)
  Dunkirk          51.03, 2.33       Dunkirk port oil depot and works (v4.0 INDUSTRY cluster)
  Beckton          51.515876, 0.071965  Wikipedia, Beckton Gas Works (largest gasworks in Europe, on the Thames)

kinds (the destructible GroundStructure kind the site reuses is chosen in WorldPopulator._build_oil_fuel):
  refinery     a full refinery: distillation, cracking and a tank farm  -> GroundStructure("refinery")
  oil_depot    a fuel storage depot / marine terminal                   -> GroundStructure("oil_depot")
  tank_farm    a large independent storage tank farm                    -> GroundStructure("oil_depot")
  gasworks     a coal-gas works with telescopic holders                 -> GroundStructure("gasworks")
  petrol_depot a canning and distribution depot                         -> GroundStructure("oil_depot")
  gas_holder   an independent gasholder station                         -> GroundStructure("gasworks")

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/oil_fuel_1940.json : {"sites":[{id,name,kind,lat,lon,size,team,source}]}

Usage: python tools/make_oil_fuel_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

NOTE = ("hand-authored 1940s oil and fuel sites (no third-party licence); generated by tools/make_oil_fuel_1940.py. "
        "Positions are real WGS84 coordinates from the cited per-record source; a few inland/French positions are "
        "carried over from the hand-authored v4.0 WorldPopulator.INDUSTRY cluster and are flagged as such in the "
        "record's source field rather than presented as freshly verified.")

# (id, name, kind, lat, lon, size, team, source)
SITES = [
    ("shell_haven", "Shell Haven Refinery", "refinery", 51.5052, 0.4902, 3, "Allies",
     "Wikipedia, Shell Haven (51.5052N 0.4902E; the first oil refinery on the Thames Estuary, 1916-1999, at the "
     "eastern end of Thurrock, Essex)"),
    ("coryton", "Coryton Refinery", "refinery", 51.513, 0.521, 3, "Allies",
     "Wikipedia, Coryton Refinery (51.513N 0.521E; Thames Estuary between Shell Haven and Hole Haven Creeks, "
     "Essex; kynoch/Cory Brothers depot from 1919)"),
    ("thames_haven", "Thames Haven oil storage depot (LT&SR)", "tank_farm", 51.51298, 0.49752, 2, "Allies",
     "Geograph TQ734823 (Oil Storage Depot) WGS84 51:30.78N 0:29.85E; Wikipedia, Shell Haven (Thames Haven was "
     "the London, Tilbury and Southend Railway port immediately east of Shell Haven, built in the 1850s)"),
    ("fawley", "Fawley Refinery", "refinery", 50.835, -1.345, 3, "Allies",
     "Esso Fawley Refinery, Southampton Water, Hampshire (position from the hand-authored v4.0 "
     "WorldPopulator.INDUSTRY cluster; not independently re-verified in this pass)"),
    ("southampton_oil", "Southampton Water oil terminal", "oil_depot", 50.895, -1.40, 2, "Allies",
     "Fawley / Southampton Water marine oil terminal (position from the hand-authored v4.0 WorldPopulator.INDUSTRY "
     "cluster; not independently re-verified in this pass)"),
    ("port_jerome", "Port-Jérôme Refinery (Notre-Dame-de-Gravenchon)", "refinery", 49.4695, 0.5353, 3, "Axis",
     "Wikipedia, Notre-Dame-de-Gravenchon (49.4695N 0.5353E; the Port-Jérôme-Gravenchon refinery on the Seine, "
     "Seine-Maritime, France)"),
    ("rouen", "Rouen Seine refineries", "refinery", 49.37, 1.07, 3, "Axis",
     "Lower Seine refinery zone at Rouen, Seine-Maritime, France (position from the hand-authored v4.0 "
     "WorldPopulator.INDUSTRY cluster)"),
    ("antwerp", "Antwerp Scheldt refineries", "refinery", 51.26, 4.35, 3, "Axis",
     "Antwerp Scheldt oil and chemical works, Belgium (position from the hand-authored v4.0 WorldPopulator.INDUSTRY "
     "cluster)"),
    ("dunkirk", "Dunkirk oil depot", "oil_depot", 51.03, 2.33, 2, "Axis",
     "Dunkirk port oil depot and works, Nord, France (position from the hand-authored v4.0 "
     "WorldPopulator.INDUSTRY cluster)"),
    ("beckton", "Beckton Gas Works", "gasworks", 51.515876, 0.071965, 3, "Allies",
     "Wikipedia, Beckton Gas Works (51.515876N 0.071965E; the Gas Light and Coke Company's works, the largest "
     "gasworks in Europe, on the Thames east of London)"),
]

KINDS = ("refinery", "oil_depot", "tank_farm", "gasworks", "petrol_depot", "gas_holder")


def main():
    recs = []
    for rid, name, kind, lat, lon, size, team, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert team in ("Axis", "Allies"), f"{rid}: bad team {team}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, size=size, team=team, source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in ("refinery", "oil_depot", "gasworks"):
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    _write("oil_fuel_1940.json", {"_note": NOTE, "sites": recs})
    print(f"oil_fuel_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
