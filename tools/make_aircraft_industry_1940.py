KINDS = ("shadow_factory", "assembly_plant", "engine_works", "dispersal_site", "aircraft_depot")


def main():
    recs = []
    for rid, name, kind, lat, lon, size, team, source in SITES:
        assert kind in KINDS, f"{rid}: bad kind {kind}"
        assert 1 <= size <= 3, f"{rid}: bad size {size}"
        assert team in ("Axis", "Allies"), f"{rid}: bad team {team}"
        assert -4.6 <= lon <= 9.0 and 48.9 <= lat <= 53.0, f"{rid}: lat/lon out of bounds"
        recs.append(dict(id=rid, name=name, kind=kind, lat=lat, lon=lon, size=size, team=team, source=source))
    ids = [r["id"] for r in recs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for k in KINDS:
        assert any(r["kind"] == k for r in recs), f"no record of kind {k}"
    _write("aircraft_industry_1940.json", {"_note": NOTE, "sites": recs})
    print(f"aircraft_industry_1940.json: {len(recs)} sites")


def _write(name, obj):
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"  wrote {path}")


if __name__ == "__main__":
    main()
