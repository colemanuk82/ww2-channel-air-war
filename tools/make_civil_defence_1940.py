#!/usr/bin/env python3
"""Hand-authored 1940s civil-defence dataset for the Channel theatre (P15).

PROVENANCE
----------
Real, documented civil-defence provision, cited per record. Positions are real WGS84 coordinates at the
town / district level (the shelter, post or sandbagging is placed by seed around that point). The
camouflage-painted factory roofs are NOT in this file - they are driven at runtime off the existing industry
and aircraft-industry sites (see CivilDefenceKit.camouflage_roof), as the brief requires.

Kinds:
  surface_shelter       a public surface / communal air-raid shelter (low brick box, blast slab, baffled entrance)
  anderson_shelter      an Anderson garden shelter (sunk, earth-mounded corrugated-steel shelter)
  arp_post              an ARP / wardens' post (control hut, look-out slit, sign board, alarm post)
  sandbagged_building   a sandbagged public building (sandbags banked against the ground floor)

OUTPUT (deterministic - no RNG, fixed ordering; re-running reproduces byte-identical JSON):
  data/civil_defence_1940.json : {"sites":[{id,name,kind,lat,lon,size,team,source}]}

Usage: python tools/make_civil_defence_1940.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

